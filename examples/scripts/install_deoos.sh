#!/bin/sh
# Install deoos the way the deoos README describes for release 0.8.0.
# The SDKs are not on PyPI or npm. pip install deoos and npm install deoos
# do not install this project. This script downloads the archive for this
# machine, checks SHA256SUMS, then installs that wheel, that Node tarball,
# and deoos-server.
set -eu
cd "$(dirname "$0")/.."

version=$(awk -F= '$1=="version"{print $2}' deoos.lock)
git_ref=$(awk -F= '$1=="git"{print $2}' deoos.lock)
os=$(uname -s)
arch=$(uname -m)
case "$os-$arch" in
  Linux-x86_64) target=linux-x64 ;;
  Linux-aarch64|Linux-arm64) target=linux-arm64 ;;
  Darwin-arm64) target=macos-arm64 ;;
  Darwin-x86_64) target=macos-x64 ;;
  *) echo "No ${version} build for $os $arch. Shipped: linux-x64, linux-arm64, macos-arm64, macos-x64, windows-x64." >&2; exit 1 ;;
esac
archive="deoos-${version}-${target}.tar.gz"
base="https://github.com/deoos-dev/deoos/releases/download/${version}"

mkdir -p .deoos/cache .deoos/release .venv
if ! [ -x .deoos/release/bin/deoos-server ] || ! grep -qx "$version $git_ref" .deoos/VERSION 2>/dev/null; then
  echo "Downloading deoos ${version} (${git_ref}) for ${target}"
  curl -fL --retry 3 -o ".deoos/cache/$archive" "$base/$archive"
  curl -fsSL --retry 3 -o .deoos/cache/SHA256SUMS "$base/SHA256SUMS"
  # Same check as the deoos README: the SHA256SUMS line for this archive.
  grep "  ${archive}$" .deoos/cache/SHA256SUMS > .deoos/cache/selected.sha256
  if [ ! -s .deoos/cache/selected.sha256 ]; then
    echo "SHA256SUMS has no entry for ${archive}" >&2
    exit 1
  fi
  if command -v sha256sum >/dev/null 2>&1; then
    (cd .deoos/cache && sha256sum -c selected.sha256)
  else
    (cd .deoos/cache && shasum -a 256 -c selected.sha256)
  fi
  rm -rf .deoos/release
  mkdir -p .deoos/release
  tar -xzf ".deoos/cache/$archive" --strip-components=1 -C .deoos/release
  printf '%s %s\n' "$version" "$git_ref" > .deoos/VERSION
fi

python3 -m venv .venv
.venv/bin/python -m pip install --disable-pip-version-check -q .deoos/release/python/*.whl -r tests/requirements.txt
npm install --no-audit --no-fund
npm install --no-audit --no-fund --no-save .deoos/release/node/*.tgz

.deoos/release/bin/deoos-server --version
.venv/bin/python -m deoos --help >/dev/null
.venv/bin/python -c "import importlib.metadata as meta; raise SystemExit(0 if meta.version('deoos') == '${version}' else 'wheel version mismatch')"
node --input-type=module -e "import { Client } from 'deoos'; if (typeof Client !== 'function') process.exit(1); console.log('node deoos client ok')"

root=$(pwd)
cat > .deoos/env.sh <<EOF
# Generated by scripts/install_deoos.sh. Source this file.
export ENGINE_BINARY='$root/.deoos/release/bin/deoos-server'
export DEOOS_NODE_SDK='$root/node_modules/deoos/dist/index.js'
export DEOOS_NODE_PACKAGE='$root/node_modules/deoos'
export PATH='$root/.venv/bin:$root/.deoos/release/bin:'"\$PATH"
EOF
echo "Installed deoos ${version} (${git_ref}) from ${archive} after SHA256SUMS. Source .deoos/env.sh before running examples."
